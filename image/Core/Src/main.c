void MP3_Send_Cmd(uint8_t cmd, uint8_t *data, uint8_t data_len) {
    uint8_t send_buf[32] = {0};
    uint8_t idx = 0;
    uint8_t check_sum = 0;
    
    send_buf[idx++] = MP3_START_CODE;
    uint8_t frame_len = 7 + data_len;
    send_buf[idx++] = frame_len;
    send_buf[idx++] = (MP3_DEV_ADDR >> 8) & 0xFF;
    send_buf[idx++] = MP3_DEV_ADDR & 0xFF;
    send_buf[idx++] = cmd;
    
    for(uint8_t i=0; i<data_len; i++) {
        send_buf[idx++] = data[i];
    }
    
    for(uint8_t i=0; i<idx; i++) {
        check_sum += send_buf[i];
    }
    send_buf[idx++] = check_sum;
    send_buf[idx++] = MP3_END_CODE;
    
    HAL_UART_Transmit(MP3_UART, send_buf, idx, 100);
}

void MP3_Play(void) {
    uint8_t data[2] = {0x00, 0x01}; 
    MP3_Send_Cmd(0x07, data, 2);
    music_status = MUSIC_PLAYING;
}

void MP3_Pause(void) {
    MP3_Send_Cmd(0x03, NULL, 0);
    music_status = MUSIC_PAUSE;
}

void MP3_Stop(void) {
    MP3_Send_Cmd(0x04, NULL, 0);
    music_status = MUSIC_STOP;
}

