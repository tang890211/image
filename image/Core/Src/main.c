void Key_Scan(void) {
    static uint32_t key_last_tick = 0;
    if(HAL_GetTick() - key_last_tick < 20) return;
    key_last_tick = HAL_GetTick();
    if(safe_mode_flag == 1) {
        if(READ_KEY_UP() == GPIO_PIN_RESET) {
            current_img_index = (current_img_index == 0) ? 1 : 0;
            uint32_t img_addr = (uint32_t)current_img_index * SINGLE_IMG_SIZE;
            Display_Image_From_Flash(img_addr);
            OLED_Show_Safe_Mode();
            while(READ_KEY_UP() == GPIO_PIN_RESET);
        }
        if(READ_KEY_DOWN() == GPIO_PIN_RESET) {
            current_img_index = (current_img_index == 1) ? 0 : 1;
            uint32_t img_addr = (uint32_t)current_img_index * SINGLE_IMG_SIZE;
            Display_Image_From_Flash(img_addr);
            OLED_Show_Safe_Mode();
            while(READ_KEY_DOWN() == GPIO_PIN_RESET);
        }
        return; 
    }
    if(READ_KEY_UP() == GPIO_PIN_RESET) {
        current_img_index = (current_img_index == 0) ? (TOTAL_IMAGES - 1) : (current_img_index - 1);
        uint32_t img_addr = (uint32_t)current_img_index * SINGLE_IMG_SIZE;
        Display_Image_From_Flash(img_addr);
        OLED_Show_Normal_Mode();
        while(READ_KEY_UP() == GPIO_PIN_RESET);
    }

    if(READ_KEY_DOWN() == GPIO_PIN_RESET) {
        current_img_index = (current_img_index + 1) % TOTAL_IMAGES;
        uint32_t img_addr = (uint32_t)current_img_index * SINGLE_IMG_SIZE;
        Display_Image_From_Flash(img_addr);
        OLED_Show_Normal_Mode();
        while(READ_KEY_DOWN() == GPIO_PIN_RESET);
    }
    if(READ_KEY_MUSIC() == GPIO_PIN_RESET) {
        if(music_status == MUSIC_PLAYING) {
            MP3_Pause();
        } else {
            MP3_Play();
        }
        OLED_Show_Normal_Mode();
        while(READ_KEY_MUSIC() == GPIO_PIN_RESET);
    }
    if(READ_KEY_SAFE() == GPIO_PIN_RESET) {
        safe_mode_flag = 1;
        MP3_Stop(); 
        current_img_index = 0;
        uint32_t img_addr = (uint32_t)current_img_index * SINGLE_IMG_SIZE;
        Display_Image_From_Flash(img_addr);
        OLED_Show_Safe_Mode();
        while(READ_KEY_SAFE() == GPIO_PIN_RESET);
    }
}
