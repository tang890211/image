void W25QXX_Read(uint8_t* pBuffer, uint32_t ReadAddr, uint16_t NumByteToRead) {
    uint8_t cmd[4];
    cmd[0] = 0x03;
    cmd[1] = (uint8_t)(ReadAddr >> 16); 
    cmd[2] = (uint8_t)(ReadAddr >> 8);  
    cmd[3] = (uint8_t)ReadAddr;         

    HAL_GPIO_WritePin(FLASH_CS_PORT, FLASH_CS_PIN, GPIO_PIN_RESET);
    HAL_SPI_Transmit(&hspi2, cmd, 4, 100);
    HAL_SPI_Receive(&hspi2, pBuffer, NumByteToRead, 1000);
    HAL_GPIO_WritePin(FLASH_CS_PORT, FLASH_CS_PIN, GPIO_PIN_SET);
}
void Display_Image_From_Flash(uint32_t flash_addr) {
    LCD_Set_Window(0, 0, IMG_WIDTH - 1, IMG_HEIGHT - 1);
    
    HAL_GPIO_WritePin(LCD_CS_PORT, LCD_CS_PIN, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LCD_RS_PORT, LCD_RS_PIN, GPIO_PIN_SET);
    W25QXX_Read((uint8_t*)line_buffer1, flash_addr, IMG_WIDTH * 2);

    for (int y = 0; y < IMG_HEIGHT; y++) {
        uint16_t *p_send = (y % 2 == 0) ? line_buffer1 : line_buffer2;
        uint16_t *p_read = (y % 2 == 0) ? line_buffer2 : line_buffer1;

        spi_dma_tx_complete = 0;
        HAL_SPI_Transmit_DMA(&hspi1, (uint8_t*)p_send, IMG_WIDTH * 2);

        if (y < IMG_HEIGHT - 1) {
            W25QXX_Read((uint8_t*)p_read, flash_addr + ((y+1) * IMG_WIDTH * 2), IMG_WIDTH * 2);
        }

        while(spi_dma_tx_complete == 0);
    }
    while (__HAL_SPI_GET_FLAG(&hspi1, SPI_FLAG_BSY) != RESET);

    HAL_GPIO_WritePin(LCD_CS_PORT, LCD_CS_PIN, GPIO_PIN_SET);
}

void HAL_SPI_TxCpltCallback(SPI_HandleTypeDef *hspi) {
    if(hspi->Instance == SPI1) {
        spi_dma_tx_complete = 1;
    }
}

